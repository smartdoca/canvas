import { test, expect } from './fixtures.mjs'
test.setTimeout(30000)

async function open(page) {
  await page.context().route('**/examples/doca/main.jsx', async route => {
    const response = await route.fetch()
    await route.fulfill({ response, body: (await response.text()).replaceAll('/dist/index.js', '/src/index.ts').replaceAll('/dist/model.js', '/src/model/index.ts').replaceAll('/dist/io.js', '/src/io/index.ts').replaceAll('/dist/index.css', '/src/index.css') })
  })
  await page.goto('/examples/doca/')
  await page.waitForFunction(() => window.demo?.handle)
  await page.evaluate(async () => {
    window.demo.model.remove(window.demo.model.getValue().scene.children.map(node => node.id))
    const { makeConnector } = await import('/src/editor/runtime/thinking/scene.ts')
    window.demo.handle.addElement({ id: 'label-backdrop', tag: 'Rect', x: 250, y: 180, width: 700, height: 420, fill: '#ffe5e3', editable: true })
    const line = makeConnector({ x: 480, y: 220 }, { x: 480, y: 560 }, 'straight')
    window.demo.handle.addElement(line.toJSON()); line.destroy()
    window.demo.handle.select([]); window.demo.handle.flush()
  })
}
const scene = page => page.evaluate(() => window.demo.model.getValue().scene.children)
const label = async page => (await scene(page)).find(node => node.data?.kind === 'connector-label')
async function clickLabel(page, id, count = 1) {
  const bounds = await page.evaluate(id => window.demo.handle.revealElements([id]).bounds, id)
  await page.locator('.canvas-host').click({ clickCount: count, position: { x: bounds.x + bounds.width / 2, y: bounds.y + bounds.height / 2 } })
}

test('connector labels stay readable without a background and support moving, undo and reopening', async ({ page }, info) => {
  await open(page)
  await page.locator('.canvas-host').dblclick({ position: { x: 480, y: 390 } })
  const input = page.locator('.canvas-plain-text-editor')
  await expect(input).toBeFocused()
  await input.fill('连线说明')
  await expect(input).toHaveCSS('color', 'rgb(65, 69, 76)')
  await expect(input).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  await page.keyboard.press('Escape')
  await page.evaluate(() => window.demo.handle.flush())
  const initial = await label(page)
  const initialLine = (await scene(page)).find(node => node.data?.kind === 'connector')
  expect(initial.children[0].text).toBe('连线说明')
  await page.screenshot({ path: info.outputPath('connector-label-before-drag.png') })
  expect(initial.fill).toBe('rgba(0,0,0,0)')
  const host = await page.locator('.canvas-host').boundingBox()
  const bounds = await page.evaluate(id => window.demo.handle.revealElements([id]).bounds, initial.id)
  const start = { x: host.x + bounds.x + bounds.width / 2, y: host.y + bounds.y + bounds.height / 2 }
  await page.mouse.move(start.x, start.y); await page.mouse.down()
  await page.mouse.move(start.x + 110, start.y - 65, { steps: 12 }); await page.mouse.up()
  await page.evaluate(() => window.demo.handle.flush())
  const moved = await label(page)
  expect((await page.evaluate(() => window.demo.handle.getSelection()))[0].id).toBe(initial.id)
  expect(moved.x).toBeCloseTo(initial.x + 110, 0)
  expect(moved.y).toBeCloseTo(initial.y - 65, 0)
  expect((await scene(page)).find(node => node.id === initialLine.id)).toEqual(initialLine)
  await page.evaluate(() => window.demo.handle.undo())
  expect((await label(page)).x).toBeCloseTo(initial.x, 0)
  expect((await label(page)).y).toBeCloseTo(initial.y, 0)
  await page.evaluate(() => window.demo.handle.redo())
  expect((await label(page)).x).toBeCloseTo(moved.x, 0)
  await page.evaluate(() => { const reopen = window.demo.openDocument, checkpoint = window.demo.closeDocument(); reopen(checkpoint) })
  expect((await label(page)).data.offset).toEqual(moved.data.offset)
  await clickLabel(page, moved.id, 2)
  await expect(input).toBeFocused()
  await expect(input).toHaveText('连线说明')
  await input.fill('调整后的说明\n第二行')
  await page.keyboard.press('Escape'); await page.evaluate(() => window.demo.handle.flush())
  const edited = await label(page)
  expect(edited.children[0].text).toBe('调整后的说明\n第二行')
  expect(edited.height).toBeGreaterThanOrEqual(edited.children[0].height + 8)
  expect(edited.data.offset).toEqual(moved.data.offset)
  await page.locator('.canvas-host').click({ position: { x: 1050, y: 150 } })
  await page.screenshot({ path: info.outputPath('connector-label-moved.png') })
})

test('legacy labels are transparent, drag at zoom, and retain their offset when bound connectors change', async ({ page }, info) => {
  await open(page)
  const { lineId, sourceId } = await page.evaluate(async () => {
    const { makeDiagram, makeConnector } = await import('/src/editor/runtime/thinking/scene.ts')
    const previous = window.demo.model.getValue().scene.children.find(node => node.data?.kind === 'connector')
    window.demo.model.remove([previous.id])
    const source = makeDiagram('rounded', 300, 260, '起点'), target = makeDiagram('rounded', 740, 420, '终点')
    const line = makeConnector({ x: 460, y: 300 }, { x: 740, y: 460 }, 'elbow', source.id, target.id)
    line.data = { ...line.data, sourceAnchor: { x: 1, y: .5 }, targetAnchor: { x: 0, y: .5 }, labelId: 'legacy-label' }
    for (const item of [source, target, line]) window.demo.model.add(item.toJSON())
    window.demo.model.add({ id: 'legacy-label', tag: 'Frame', name: 'connector-label', x: 552, y: 366, width: 96, height: 28, fill: '#ffffff', editable: false, hitSelf: false, hitChildren: false, data: { kind: 'connector-label', ownerId: line.id }, children: [{ id: 'legacy-label-text', tag: 'Text', name: 'text', text: '已有说明', x: 5, y: 4, width: 86, height: 20, fontSize: 13, fill: '#41454c', textAlign: 'center', verticalAlign: 'middle', data: { kind: 'node-label' } }] })
    const result = { lineId: line.id, sourceId: source.id }
    for (const item of [source, target, line]) item.destroy()
    window.demo.handle.flush()
    return result
  })
  expect(await page.evaluate(() => window.demo.handle.getValue().scene.children.find(node => node.id === 'legacy-label').fill)).toBe('rgba(0,0,0,0)')
  const host = await page.locator('.canvas-host').boundingBox()
  const bounds = await page.evaluate(() => window.demo.handle.revealElements(['legacy-label'], { maxZoom: 2 }).bounds)
  await expect(page.locator('.zoom-value')).toHaveText('200%')
  const start = { x: host.x + bounds.x + bounds.width / 2, y: host.y + bounds.y + bounds.height / 2 }
  const delta = await page.evaluate(start => {
    const a = window.demo.handle.clientToScene(start), b = window.demo.handle.clientToScene({ x: start.x + 120, y: start.y - 60 })
    return { x: b.x - a.x, y: b.y - a.y }
  }, start)
  await page.mouse.move(start.x, start.y); await page.mouse.down()
  await page.mouse.move(start.x + 120, start.y - 60, { steps: 12 }); await page.mouse.up()
  await page.evaluate(() => window.demo.handle.flush())
  const moved = await label(page)
  expect(moved.data.offset.x).toBeCloseTo(delta.x, 1)
  expect(moved.data.offset.y).toBeCloseTo(delta.y, 1)
  await page.evaluate(sourceId => { window.demo.handle.select([sourceId]); window.demo.handle.updateSelection({ x: 340, y: 320 }); window.demo.handle.flush() }, sourceId)
  const followed = await label(page)
  expect(followed.data.offset).toEqual(moved.data.offset)
  expect(followed.x).not.toBe(moved.x)
  expect(followed.y).not.toBe(moved.y)
  await page.evaluate(lineId => window.demo.handle.select([lineId]), lineId)
  await page.getByRole('button', { name: '连线类型', exact: true }).click()
  await page.getByRole('menuitemradio', { name: '曲线', exact: true }).click()
  expect((await label(page)).data.offset).toEqual(moved.data.offset)
  await page.locator('.canvas-host').click({ position: { x: 1100, y: 150 } })
  await page.screenshot({ path: info.outputPath('connector-label-zoomed.png') })
  await page.evaluate(() => window.demo.setMode('readonly'))
  const before = await scene(page)
  await clickLabel(page, 'legacy-label', 2)
  await expect(page.locator('.leafer-text-editor')).toHaveCount(0)
  expect(await scene(page)).toEqual(before)
})
