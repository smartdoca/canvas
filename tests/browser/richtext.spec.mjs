import { test, expect } from './fixtures.mjs'
test.setTimeout(20000)

async function open(page) {
  await page.context().route('**/examples/doca/main.jsx', async route => {
    const response = await route.fetch()
    await route.fulfill({ response, body: (await response.text()).replaceAll('/dist/index.js', '/src/index.ts').replaceAll('/dist/model.js', '/src/model/index.ts').replaceAll('/dist/io.js', '/src/io/index.ts').replaceAll('/dist/index.css', '/src/index.css') })
  })
  await page.goto('/examples/doca/')
  await page.waitForFunction(() => window.demo?.handle)
}
const value = page => page.evaluate(() => window.demo.model.getValue())
const find = (nodes, id) => { for (const node of nodes) { if (node.id === id) return node; const child = node.children && find(node.children, id); if (child) return child } }
const richNote = (page, text) => page.evaluate(text => {
  const id = crypto.randomUUID()
  window.demo.model.add({ tag: 'Frame', name: 'note', x: 350, y: 260, width: 360, height: 180, fill: '#fff2a8', editable: true, data: { kind: 'note' }, children: [{ id, tag: 'Text', name: 'text', text, x: 16, y: 16, width: 328, height: 148, fontSize: 20, fill: '#1f2329', editable: true }] })
  return id
}, text)
async function edit(page, id) {
  const box = await page.evaluate(id => window.demo.handle.revealElements([id]).bounds, id)
  await page.locator('.canvas-host').dblclick({ position: { x: box.x + box.width / 2, y: box.y + box.height / 2 } })
  await expect(page.locator('[data-slate-editor]')).toBeFocused()
}

test('Slate partial marks survive close, undo, checkpoint reopen and styled SVG/PNG export', async ({ page }, info) => {
  await open(page)
  await page.evaluate(() => window.demo.model.remove(window.demo.model.getValue().scene.children.map(node => node.id)))
  const id = await richNote(page, '产品方向与关键行动')
  await edit(page, id)
  const input = page.locator('[data-slate-editor]')
  await input.focus(); await page.keyboard.press('Home')
  for (let i = 0; i < 4; i++) await page.keyboard.press('Shift+ArrowRight')
  await expect.poll(() => input.evaluate(() => window.getSelection().toString())).toBe('产品方向')
  await page.getByRole('button', { name: '选中文字加粗', exact: true }).click()
  await page.getByRole('button', { name: '选中文字高亮', exact: true }).click()
  await page.getByRole('button', { name: '#fff1b8', exact: true }).click()
  await expect(input.locator('span[data-slate-leaf]').first()).toHaveCSS('font-weight', '700')
  await page.screenshot({ path: info.outputPath('slate-partial-format.png') })
  await page.keyboard.press('Escape')
  await page.evaluate(() => window.demo.handle.flush())
  let node = find((await value(page)).scene.children, id)
  expect(node.text).toBe('产品方向与关键行动')
  expect(node.data.richText.value[0].children).toEqual([{ text: '产品方向', bold: true, backgroundColor: '#fff1b8' }, { text: '与关键行动' }])
  const exported = await page.evaluate(async () => {
    const svg = await window.demo.handle.exportFile({ format: 'svg' }), png = await window.demo.handle.exportFile({ format: 'png' })
    return { svg: await svg.blob.text(), png: png.blob.size, before: window.demo.model.getValue() }
  })
  expect(exported.svg).toContain('font:700 20px'); expect(exported.svg).toContain('#fff1b8'); expect(exported.png).toBeGreaterThan(100)
  await page.evaluate(() => window.demo.handle.undo())
  node = find((await value(page)).scene.children, id)
  expect(node.text).toBe('产品方向与关键行动')
  await page.evaluate(() => window.demo.handle.redo())
  expect(find((await value(page)).scene.children, id).data.richText).toBeTruthy()
  await page.evaluate(() => { const reopen = window.demo.openDocument, checkpoint = window.demo.closeDocument(); reopen(checkpoint) }); await page.waitForFunction(() => window.demo?.handle)
  await edit(page, id)
  await expect(page.locator('[data-slate-leaf]').first()).toHaveCSS('font-weight', '700')
  await page.keyboard.press('Escape')
  expect(find((await value(page)).scene.children, id).textEditing).toBeUndefined()
})

test('Slate table Tab navigation, last-cell row growth and rectangular TSV paste use native cells', async ({ page }) => {
  await open(page)
  await page.getByRole('button', { name: '表格', exact: true }).click()
  await page.locator('.canvas-host').click({ position: { x: 700, y: 440 } })
  await expect.poll(async () => (await value(page)).scene.children.some(node => node.data?.kind === 'table')).toBe(true)
  let table = (await value(page)).scene.children.find(node => node.data?.kind === 'table')
  await edit(page, table.children[0].id)
  await page.keyboard.insertText('负责人'); await page.keyboard.press('Tab')
  await expect(page.locator('[data-slate-editor]')).toHaveText('')
  await page.keyboard.insertText('进度'); await page.keyboard.press('Shift+Tab')
  await expect(page.locator('[data-slate-editor]')).toHaveText('负责人')
  await page.locator('[data-slate-editor]').evaluate(element => {
    const clipboardData = new DataTransfer(); clipboardData.setData('text/plain', '任务\t负责人\n画布升级\t张三')
    element.dispatchEvent(new ClipboardEvent('paste', { clipboardData, bubbles: true, cancelable: true }))
  })
  await page.keyboard.press('Escape'); await page.evaluate(() => window.demo.handle.flush())
  table = (await value(page)).scene.children.find(node => node.id === table.id)
  expect(table.children.find(node => node.data.row === 0 && node.data.column === 0).children[0].text).toBe('任务')
  expect(table.children.find(node => node.data.row === 1 && node.data.column === 1).children[0].text).toBe('张三')
  await edit(page, table.children.at(-1).id)
  await page.keyboard.press('Tab'); await page.keyboard.insertText('新增行'); await page.keyboard.press('Escape')
  await page.evaluate(() => window.demo.handle.flush())
  table = (await value(page)).scene.children.find(node => node.id === table.id)
  expect(table.data.rows).toBe(4)
  expect(table.children.find(node => node.data.row === 3 && node.data.column === 0).children[0].text).toBe('新增行')
})

test('active Slate text merges remote characters, keeps rich marks and publishes no projection echoes', async ({ page, context }) => {
  await open(page)
  const id = await richNote(page, '本地')
  const peer = await context.newPage(); await peer.goto(await page.evaluate(() => window.demo.link)); await peer.waitForFunction(() => window.demo?.handle)
  await edit(page, id)
  await page.keyboard.press('Meta+b'); await page.keyboard.press('ArrowRight'); await page.keyboard.insertText('编辑')
  await page.evaluate(() => window.demo.handle.flush())
  await expect.poll(async () => find((await value(peer)).scene.children, id).text).toBe('本地编辑')
  const before = await page.evaluate(() => window.demo.allUpdates.length)
  await peer.evaluate(id => window.demo.model.editText(id, 0, 0, '远端'), id)
  await expect(page.locator('[data-slate-editor]')).toHaveText('远端本地编辑')
  expect(await page.evaluate(() => window.demo.allUpdates.length)).toBe(before)
  await page.keyboard.press('End'); await page.keyboard.insertText('完成')
  await page.evaluate(() => window.demo.handle.flush())
  await page.keyboard.press('Meta+z')
  await expect(page.locator('[data-slate-editor]')).toHaveText('远端本地编辑')
  await page.keyboard.press('Meta+Shift+z')
  await expect(page.locator('[data-slate-editor]')).toHaveText('远端本地编辑完成')
  await page.keyboard.press('Escape')
  await page.evaluate(() => window.demo.handle.flush())
  await expect.poll(async () => JSON.stringify(await value(page)) === JSON.stringify(await value(peer))).toBe(true)
  expect(find((await value(peer)).scene.children, id).text).toBe('远端本地编辑完成')
  await peer.close()
})

test('standalone rich HTML paste is sanitized, auto-saved and retains marks after reload', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '便笺 (N)', exact: true }).click()
  await page.locator('.canvas-host').click({ position: { x: 700, y: 300 } })
  await expect(page.locator('.selection-actions')).toBeVisible()
  await page.locator('.canvas-host').click({ position: { x: 700, y: 300 } })
  const input = page.locator('[data-slate-editor]')
  await expect(input).toBeFocused()
  await input.evaluate(element => {
    const clipboardData = new DataTransfer()
    clipboardData.setData('text/html', '<p><strong>重要方向</strong>与<em style="color:#3370ff">行动</em></p><script>alert(1)</script>')
    clipboardData.setData('text/plain', '重要方向与行动')
    element.dispatchEvent(new ClipboardEvent('paste', { clipboardData, bubbles: true, cancelable: true }))
  })
  await expect(input).toHaveText('重要方向与行动')
  await page.keyboard.press('Escape')
  const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('aidcanvas.document') || '{}').scene?.children?.find(node => node.name === 'note')?.children?.find(node => node.tag === 'Text'))
  await expect.poll(async () => (await saved())?.data?.richText?.value[0]?.children[0]?.bold).toBe(true)
  const before = await saved()
  expect(before.text).toBe('重要方向与行动')
  expect(JSON.stringify(before)).not.toContain('alert')
  await page.reload()
  await page.locator('.canvas-view canvas').first().waitFor()
  await page.locator('.canvas-host').dblclick({ position: { x: 730, y: 310 } })
  await expect(input).toHaveText('重要方向与行动')
  await expect(input.locator('[data-slate-leaf]').first()).toHaveCSS('font-weight', '700')
  await page.keyboard.press('Escape')
  expect(await saved()).toEqual(before)
})
