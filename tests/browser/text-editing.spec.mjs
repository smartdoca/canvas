import { test, expect } from './fixtures.mjs'

async function open(page) {
  await page.goto('/examples/doca/')
  await page.waitForFunction(() => window.demo?.handle)
}

async function clickText(page, id, clicks = 2) {
  await expect.poll(() => page.evaluate(id => Boolean(window.demo.handle.revealElements([id]).bounds), id)).toBe(true)
  const bounds = await page.evaluate(id => window.demo.handle.revealElements([id]).bounds, id)
  await page.locator('.canvas-host').click({ clickCount: clicks, position: { x: bounds.x + bounds.width / 2, y: bounds.y + bounds.height / 2 } })
}

const texts = page => page.evaluate(() => window.demo.handle.getValue().scene.children.filter(node => node.tag === 'Text'))
const control = (page, label) => page.locator('.style-control').filter({ has: page.locator('.style-label', { hasText: new RegExp(`^${label}$`) }) })
async function setSlider(page, label, steps) {
  const slider = control(page, label).locator('input[type="range"]')
  await slider.focus()
  await slider.press('Home')
  for (let index = 0; index < steps; index++) await slider.press('ArrowRight')
}

for (const creation of ['double-click', 'toolbar']) {
  test(`${creation} text: newline, line-height/font-size controls and mouse selection stay editable`, async ({ page }, testInfo) => {
    await open(page)
    if (creation === 'toolbar') await page.getByRole('button', { name: '文本 (T)', exact: true }).click()
    await page.locator('.canvas-host').click({ clickCount: creation === 'double-click' ? 2 : 1, position: { x: 700, y: 300 } })
    const input = page.locator('.leafer-text-editor')
    await expect(input).toBeFocused()
    await input.fill('导入用户照片')
    await page.keyboard.press('End')
    await page.keyboard.press('Enter')
    await page.keyboard.insertText('第二行')
    await expect(input).toHaveCSS('line-height', '21px')
    await page.evaluate(() => window.demo.handle.flush())
    const created = (await texts(page)).find(node => node.id !== 'text-a')
    expect(created.text.replaceAll('\u200b', '')).toBe('导入用户照片\n第二行')
    await page.keyboard.press('Escape')
    await expect(page.locator('.canvas-app')).toBeFocused()
    await setSlider(page, '行高', 12)
    await setSlider(page, '字体大小', 18)
    await page.evaluate(() => window.demo.handle.flush())
    expect((await texts(page)).find(node => node.id === created.id).lineHeight).toEqual({ type: 'percent', value: 2 })
    await clickText(page, created.id)
    await expect(input).toBeFocused()
    await expect(input).toHaveCSS('line-height', '56px')
    await input.dblclick({ position: { x: 14, y: 20 } })
    expect(await input.evaluate(e => e.contains(getSelection().anchorNode) && getSelection().toString().length > 0)).toBe(true)
    await page.keyboard.insertText('修改')
    await page.keyboard.press('Escape')
    await page.evaluate(() => window.demo.handle.flush())
    expect((await texts(page)).find(node => node.id === created.id).text).toContain('修改')
    const bounds = await page.evaluate(id => window.demo.handle.revealElements([id]).bounds, created.id)
    expect(bounds.height).toBeGreaterThanOrEqual(112)
    await page.screenshot({ path: testInfo.outputPath(`${creation}-multiline.png`) })
  })
}

test('saved text with the former pixel/multiplier error can be selected, edited and reopened', async ({ page }) => {
  await open(page)
  await page.evaluate(() => window.demo.model.patch('text-a', { text: '第一行\n第二行', lineHeight: 1.5, fontSize: 32 }))
  await clickText(page, 'text-a', 1)
  await page.keyboard.press('Enter')
  const input = page.locator('.leafer-text-editor')
  await expect(input).toBeFocused()
  await expect(input).toHaveCSS('line-height', '48px')
  await input.dblclick({ position: { x: 14, y: 16 } })
  expect(await page.evaluate(() => getSelection().toString().length)).toBeGreaterThan(0)
  await page.keyboard.insertText('修改')
  await page.keyboard.press('Escape')
  await page.evaluate(() => { const reopen = window.demo.openDocument, checkpoint = window.demo.closeDocument(); reopen(checkpoint) })
  await clickText(page, 'text-a')
  await expect(input).toContainText('修改')
  await expect(input).toHaveCSS('line-height', '48px')
})

test('standalone Chinese composition keeps candidate selection and does not add a newline on confirmation', async ({ page, context }) => {
  await page.goto('/')
  await page.locator('.canvas-host').dblclick({ position: { x: 700, y: 300 } })
  const input = page.locator('.leafer-text-editor')
  await expect(input).toBeFocused()
  const cdp = await context.newCDPSession(page)
  await cdp.send('Input.imeSetComposition', { text: 'zhongwen', selectionStart: 8, selectionEnd: 8 })
  expect(await input.evaluate(e => {
    const event = new KeyboardEvent('keydown', { key: 'Enter', code: 'Enter', isComposing: true, bubbles: true, cancelable: true })
    e.dispatchEvent(event)
    return event.defaultPrevented
  })).toBe(false)
  await cdp.send('Input.insertText', { text: '中文' })
  await expect(input).toHaveText('中文')
  await page.keyboard.press('Escape')
  await expect(page.locator('.canvas-app')).toBeFocused()
})

for (const modifier of ['Meta', 'Control']) {
  test(`${modifier}+C/V copies a text box with a new identity; readonly cannot paste`, async ({ page }) => {
    await open(page)
    await clickText(page, 'text-a')
    const input = page.locator('.leafer-text-editor')
    await input.fill('复制这个文本框')
    await page.keyboard.press('Escape')
    await expect(page.locator('.canvas-app')).toBeFocused()
    await page.keyboard.press(`${modifier}+c`)
    await page.keyboard.press(`${modifier}+v`)
    await expect.poll(async () => (await texts(page)).length).toBe(2)
    const nodes = await texts(page)
    expect(nodes[0].text).toBe('复制这个文本框')
    expect(nodes[1].text).toBe(nodes[0].text)
    expect(nodes[1].id).not.toBe(nodes[0].id)
    expect(nodes[1].x).toBe(nodes[0].x + 16)
    expect(nodes[1].y).toBe(nodes[0].y + 16)
    await page.evaluate(() => window.demo.setMode('readonly'))
    await expect(page.locator('.canvas-app')).toHaveClass(/is-readonly/)
    await page.keyboard.press(`${modifier}+v`)
    expect((await texts(page)).length).toBe(2)
  })
}

test('canvas clipboard supports another editor page and undo without swallowing native text paste', async ({ page, context }) => {
  await open(page)
  const second = await context.newPage()
  await open(second)
  await clickText(page, 'text-a', 1)
  await page.keyboard.press('Meta+c')
  await second.locator('.canvas-app').focus()
  await second.keyboard.press('Meta+v')
  await expect.poll(async () => (await texts(second)).length).toBe(2)
  await second.evaluate(() => { window.demo.handle.flush(); window.demo.handle.undo() })
  expect((await texts(second)).length).toBe(1)
  await clickText(second, 'text-a')
  const input = second.locator('.leafer-text-editor')
  await input.evaluate(e => {
    const data = new DataTransfer(); data.setData('text/plain', '普通文本\n粘贴')
    e.dispatchEvent(new ClipboardEvent('paste', { bubbles: true, cancelable: true, clipboardData: data }))
  })
  await expect.poll(() => input.evaluate(e => e.innerText)).toBe('普通文本\n粘贴')
  expect((await texts(second)).length).toBe(1)
  await second.close()
})

test('keyboard-pasted text group converges with a peer; child IDs and peer edits survive own undo', async ({ page, context }) => {
  await open(page)
  const peer = await context.newPage()
  await peer.goto(await page.evaluate(() => window.demo.link))
  await peer.waitForFunction(() => window.demo?.handle)
  await page.evaluate(() => { window.demo.handle.select(['rect-a', 'text-a']); window.demo.handle.groupSelection(); window.demo.handle.flush() })
  await page.locator('.canvas-app').focus()
  await page.keyboard.press('Meta+c')
  await page.keyboard.press('Meta+v')
  const groups = () => peer.evaluate(() => window.demo.model.getValue().scene.children.filter(node => node.tag === 'Group'))
  await expect.poll(async () => (await groups()).length).toBe(2)
  const [original, copy] = await groups()
  expect(copy.children.map(node => node.id).some(id => original.children.some(node => node.id === id))).toBe(false)
  expect(copy.children.find(node => node.tag === 'Text').text).toBe('hello canvas')
  await peer.evaluate(() => window.demo.model.patch('rect-a', { fill: '#ff0000' }))
  await expect.poll(() => page.evaluate(() => window.demo.model.getValue().scene.children.find(node => node.tag === 'Group').children.find(node => node.id === 'rect-a').fill)).toBe('#ff0000')
  await page.evaluate(() => window.demo.handle.undo())
  await expect.poll(async () => (await groups()).length).toBe(1)
  expect((await groups())[0].children.find(node => node.id === 'rect-a').fill).toBe('#ff0000')
  await expect.poll(async () => JSON.stringify(await page.evaluate(() => window.demo.model.getValue())) === JSON.stringify(await peer.evaluate(() => window.demo.model.getValue()))).toBe(true)
  await peer.close()
})
