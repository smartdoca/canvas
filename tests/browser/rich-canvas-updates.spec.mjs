const scene = page => page.evaluate(() => window.demo.model.getValue().scene.children)
async function open(page) {
  await page.goto('/examples/doca/'); await page.waitForFunction(() => window.demo?.handle)
  await page.evaluate(() => window.demo.model.remove(window.demo.model.getValue().scene.children.map(n => n.id)))
}
async function seed(page, value, fill = '#fff2a8', type = 'note') {
  return page.evaluate(({ value, fill, type }) => {
    const id = crypto.randomUUID(), labelId = crypto.randomUUID()
    const text = value.map(p => p.resource || p.custom ? '\uFFFC' : p.children.map(l => l.text).join('')).join('\n')
    window.demo.model.add({ id, tag: 'Frame', name: type, x: 340, y: 180, width: 320, height: 340, fill, hitChildren: false, editable: true, data: { kind: type }, children: [{ id: labelId, tag: 'Text', name: 'text', text, x: 16, y: 16, width: 288, height: 308, fontSize: 24, textAlign: 'center', verticalAlign: 'middle', fill: fill === '#3370ff' ? '#ffffff' : '#1f2329', editable: true, data: { richText: { version: 1, value } } }] })
    return { id, labelId }
  }, { value, fill, type })
}
async function edit(page, id) {
  await page.waitForFunction(id => { const find = n => n.id === id || n.children?.some(find); return find(window.demo.model.getValue().scene) }, id)
  const b = await page.evaluate(id => window.demo.handle.revealElements([id]).bounds, id)
  await page.locator('.canvas-host').dblclick({ position: { x: b.x + b.width / 2, y: b.y + b.height / 2 } })
  await expect(page.locator('[data-slate-editor]')).toBeFocused()
}
